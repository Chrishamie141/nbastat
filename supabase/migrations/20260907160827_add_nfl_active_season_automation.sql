-- Durable state for a bounded Supabase Cron -> Vercel REST automation.
-- No policies are intentionally created: only the direct server connection may
-- read or write these operational tables.
create table if not exists public.nfl_automation_state (
  singleton integer primary key check (singleton = 1),
  enabled integer not null default 1,
  active_experiment_key text,
  last_context_refresh_at text,
  last_tick_started_at text,
  last_tick_completed_at text,
  last_status text not null default 'BOOTSTRAP',
  last_error_code text,
  last_provider_contact_at text,
  next_due_at text,
  updated_at text not null
);

create table if not exists public.nfl_capture_experiments (
  experiment_key text primary key,
  season integer not null,
  season_type text not null check (season_type in ('preseason','regular','postseason')),
  display_week integer not null,
  provider_week integer not null,
  status text not null,
  manifest_json text not null,
  manifest_hash text not null,
  credits_limit integer not null check (credits_limit >= 3),
  credits_reserved integer not null default 0 check (credits_reserved >= 0),
  provider_remaining integer,
  quota_state text not null default 'BOOTSTRAP',
  created_at text not null,
  sealed_at text,
  unique (season, season_type, display_week)
);

create table if not exists public.nfl_capture_games (
  experiment_key text not null references public.nfl_capture_experiments(experiment_key),
  game_id text not null,
  home_team text not null,
  away_team text not null,
  kickoff text not null,
  kickoff_epoch double precision not null,
  schedule_hash text not null,
  status text not null default 'SCHEDULED',
  primary key (experiment_key, game_id)
);

create table if not exists public.nfl_capture_checkpoints (
  experiment_key text not null,
  game_id text not null,
  offset_minutes integer not null,
  due_at text not null,
  due_epoch double precision not null,
  deadline_at text not null,
  deadline_epoch double precision not null,
  state text not null default 'PENDING',
  attempt_count integer not null default 0,
  last_attempt_at text,
  primary key (experiment_key, game_id, offset_minutes),
  foreign key (experiment_key, game_id)
    references public.nfl_capture_games(experiment_key, game_id)
);

create table if not exists public.nfl_capture_requests (
  id bigint generated by default as identity primary key,
  request_key text not null unique,
  experiment_key text not null references public.nfl_capture_experiments(experiment_key),
  requested_at text not null,
  completed_at text,
  state text not null,
  credits_reserved integer not null,
  remaining integer,
  used integer,
  last_cost integer,
  response_hash text,
  http_status integer
);

create table if not exists public.nfl_capture_markets (
  capture_key text primary key,
  experiment_key text not null,
  game_id text not null,
  offset_minutes integer not null,
  request_id bigint not null references public.nfl_capture_requests(id),
  retrieved_at text not null,
  stored_at text not null,
  kickoff text not null,
  cutoff_epoch double precision not null,
  deadline_epoch double precision not null,
  event_id text not null,
  bookmaker text not null,
  market_type text not null check (market_type in ('h2h','spreads','totals')),
  source_time text not null,
  source_epoch double precision not null,
  retrieved_epoch double precision not null,
  outcomes_json text not null,
  provenance_json text not null,
  unique (experiment_key, game_id, offset_minutes, bookmaker, market_type),
  foreign key (experiment_key, game_id, offset_minutes)
    references public.nfl_capture_checkpoints(experiment_key, game_id, offset_minutes)
);

create table if not exists public.nfl_capture_quotes (
  capture_key text not null references public.nfl_capture_markets(capture_key),
  side text not null,
  line double precision,
  price double precision not null,
  primary key (capture_key, side)
);

create table if not exists public.nfl_automation_events (
