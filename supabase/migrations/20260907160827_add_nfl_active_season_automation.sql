create or replace function smartbets_internal.block_immutable_capture()
returns trigger
language plpgsql
set search_path = pg_catalog
as $$
begin
  raise exception 'immutable NFL market evidence';
end
$$;

create or replace function smartbets_internal.enforce_pregame_capture()
returns trigger
language plpgsql
set search_path = pg_catalog, public
as $$
begin
  if extract(epoch from clock_timestamp()) >= new.cutoff_epoch
     or new.retrieved_epoch >= new.cutoff_epoch
     or new.source_epoch >= new.cutoff_epoch
     or new.source_epoch > new.retrieved_epoch
     or extract(epoch from clock_timestamp()) >= new.deadline_epoch
     or new.retrieved_epoch >= new.deadline_epoch then
    raise exception 'pregame write boundary';
  end if;
  return new;
end
$$;

create or replace function smartbets_internal.enforce_pregame_quote()
returns trigger
language plpgsql
set search_path = pg_catalog, public
as $$
declare
  evidence_cutoff double precision;
  evidence_deadline double precision;
begin
  select cutoff_epoch, deadline_epoch
    into evidence_cutoff, evidence_deadline
    from public.nfl_capture_markets
   where capture_key = new.capture_key;
  if evidence_cutoff is null
     or extract(epoch from clock_timestamp()) >= evidence_cutoff
     or extract(epoch from clock_timestamp()) >= evidence_deadline then
    raise exception 'pregame write boundary';
  end if;
  return new;
end
$$;

create or replace function smartbets_internal.protect_nfl_experiment()
returns trigger
language plpgsql
set search_path = pg_catalog
as $$
begin
  if old.manifest_json is distinct from new.manifest_json
     or old.manifest_hash is distinct from new.manifest_hash
     or old.season is distinct from new.season
     or old.season_type is distinct from new.season_type
     or old.display_week is distinct from new.display_week
     or old.provider_week is distinct from new.provider_week
     or old.credits_limit is distinct from new.credits_limit then
    raise exception 'immutable NFL experiment manifest';
  end if;
  return new;
end
$$;

