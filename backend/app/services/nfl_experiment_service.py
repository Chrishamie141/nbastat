def experiment_dashboard(season: int = 2026, season_type: str = "preseason",
                         display_week: int = 3, refresh: bool = True) -> dict:
    initialize_experiment_database()
    refresh_error = None
    if refresh:
        try:
            sync_experiment_schedule(season, season_type, display_week)
        except Exception as exc:  # dashboard still serves stored audit evidence
            refresh_error = type(exc).__name__
            logger.exception("experiment_schedule_refresh_failed experiment=%s",
                             _experiment_key(season, season_type, display_week))
    integrity = experiment_integrity(season, season_type, display_week)
    grading_error = None
    if integrity.get("verified"):
        try:
            grade_experiment(season, season_type, display_week)
        except Exception as exc:
            grading_error = type(exc).__name__
            logger.exception("experiment_grading_failed experiment=%s", integrity["experimentKey"])
    else:
        grading_error = "BASELINE_HASH_MISMATCH"
    key = integrity["experimentKey"]
    predictions = _prediction_rows(season, season_type, display_week)
    with get_db_connection() as connection:
        results = {row["game_id"]: row for row in connection.execute(
            "SELECT * FROM nfl_game_results WHERE season=? AND season_type=? AND display_week=?",
            (season, season_type, display_week),
        ).fetchall()}
        grades = {row["game_id"]: row for row in connection.execute(
            "SELECT * FROM nfl_experiment_grades WHERE experiment_key=?", (key,)
        ).fetchall()}
        schedule = {row["game_id"]: row for row in connection.execute(
            "SELECT * FROM nfl_game_schedule_state WHERE season=? AND season_type=? AND display_week=?",
            (season, season_type, display_week),
        ).fetchall()}
        last_refresh = connection.execute(
            """SELECT refreshed_at,state FROM nfl_schedule_refreshes WHERE season=? AND season_type=?
            ORDER BY refreshed_at DESC,id DESC LIMIT 1""", (season, season_type)
        ).fetchone()
    games = []
    for row in predictions:
        prediction = json.loads(row["prediction_json"])
        result, grade, state = results.get(row["game_id"]), grades.get(row["game_id"]), schedule.get(row["game_id"])
        history = market_history_for_game(row["game_id"], row["kickoff_time"])
        frozen_winner = prediction.get("winner")
        home_team = result["home_team"] if result else state["home_team"] if state else None
        away_team = result["away_team"] if result else state["away_team"] if state else None
        entry, current_entry_price, current_edge = _qualified_entry(
            prediction, {"game_id": row["game_id"], "home_team": home_team}, history,
            integrity["evaluationProfile"],
        )
        game_view = {"gameId": row["game_id"], "matchup": None,
                     "homeTeam": home_team, "awayTeam": away_team,
                     "frozenWinner": frozen_winner, "frozenProbability": prediction.get("winProbability"),
                     "frozenRating": prediction.get("rating"), "riskLevel": prediction.get("riskLevel"),
                     "frozenReasoning": prediction.get("reasons"),
                     "frozenEvidence": prediction.get("evidenceScore"), "frozenMainRisk": prediction.get("mainRisk"),
                     "frozenMissingData": prediction.get("missingData"), "modelVersion": row["model_version"],
                     "modelGeneratedAt": row["generated_at"], "dataTimestamp": prediction.get("dataAsOf"),
                     "marketHistory": history,
                     "firstPrice": None, "latestPregamePrice": None, "closingPrice": grade["closing_price"] if grade else None,
                     "entryPrice": grade["entry_price"] if grade else current_entry_price,
                     "modelEdge": grade["model_edge"] if grade else current_edge if entry else prediction.get("edge"),
                     "betDecision": "BET" if (grade and grade["qualified_wager"]) or entry else "PASS",
                     "actualScore": None if not result else f"{result['away_team']} {result['away_score']} - {result['home_team']} {result['home_score']}",
                     "predictionResult": grade["prediction_result"] if grade else "PENDING",
                     "qualifiedWagerResult": grade["wager_result"] if grade else "PENDING",
                     "units": grade["net_units"] if grade else None,
                     "state": "GRADED" if grade else state["status"].upper() if state else "SCHEDULED"}
        if game_view["awayTeam"] and game_view["homeTeam"]:
            game_view["matchup"] = f"{game_view['awayTeam']} at {game_view['homeTeam']}"
        for field, observation in (("firstPrice", history.get("first")), ("latestPregamePrice", history.get("latest"))):
            if observation:
                price, _ = _winner_price_and_edge(prediction, {"home_team": game_view["homeTeam"]}, observation)
                game_view[field] = price
        if game_view["closingPrice"] is None and history.get("closing"):
            game_view["closingPrice"], _ = _winner_price_and_edge(
                prediction, {"home_team": game_view["homeTeam"]}, history["closing"]
            )
        games.append(game_view)
    graded_rows = [game for game in games if game["predictionResult"] in {"WIN", "LOSS", "PUSH"}]
    wins = sum(game["predictionResult"] == "WIN" for game in graded_rows)
    losses = sum(game["predictionResult"] == "LOSS" for game in graded_rows)
    pushes = sum(game["predictionResult"] == "PUSH" for game in graded_rows)
    qualified = [game for game in games if game["qualifiedWagerResult"] in {"WIN", "LOSS", "PUSH"}]
    bet_wins = sum(game["qualifiedWagerResult"] == "WIN" for game in qualified)
    bet_losses = sum(game["qualifiedWagerResult"] == "LOSS" for game in qualified)
    bet_pushes = sum(game["qualifiedWagerResult"] == "PUSH" for game in qualified)
    net_units = round(sum(float(game["units"] or 0) for game in qualified), 4)
    risked = float(len(qualified))
    calibration_rows = [{"predictionResult": game["predictionResult"],
                         "probability": game["frozenProbability"]} for game in graded_rows]
    segment_rows = [{"predictionResult": game["predictionResult"], "riskLevel": game.get("riskLevel"),
                     "entryPrice": game.get("entryPrice"), "modelEdge": game.get("modelEdge")}
                    for game in graded_rows]
    provider = latest_provider_health()
    final_count = len(results)
    experiment_status = ("COMPLETE" if final_count == len(predictions) and predictions else
                         "IN_PROGRESS" if final_count else "COLLECTING")
    canonical_week = ("HOF" if display_week == 0 else f"PRE{display_week}") if season_type == "preseason" else f"REG{display_week}"
    return {
        "experiment": {"key": key, "canonicalWeek": canonical_week,
                       "experimentStatus": experiment_status, "baselineLocked": True, **integrity},
        "metrics": {"finalGameCount": final_count, "predictionsGraded": len(graded_rows),
                    "correctPredictions": wins, "incorrectPredictions": losses, "pushes": pushes,
                    "winnerAccuracy": round(wins / (wins + losses) * 100, 1) if wins + losses else None,
                    "qualifiedBetCount": len(qualified),
                    "qualifiedBetRecord": {"wins": bet_wins, "losses": bet_losses, "pushes": bet_pushes},
                    "units": net_units if qualified else None,
                    "roi": round(net_units / risked * 100, 1) if risked else None,
                    "marketCoverage": {"games": sum(game["marketHistory"]["count"] > 0 for game in games),
                                       "total": len(games)},
                    "closingPricesCaptured": sum(game["marketHistory"]["closing"] is not None for game in games),
                    "gradingStatus": "BLOCKED_INTEGRITY" if not integrity["verified"] else
                                     "COMPLETE" if len(graded_rows) == len(predictions) and predictions else
                                     "PARTIAL" if graded_rows else "PENDING"},
        "providerHealth": provider,
        "operations": {"lastScheduleRefresh": last_refresh["refreshed_at"] if last_refresh else None,
                       "scheduleRefreshState": last_refresh["state"] if last_refresh else None,
                       "scheduleRefreshError": refresh_error, "gradingError": grading_error},
        "games": games,
        "calibration": {"status": "SUFFICIENT_SAMPLE" if len(graded_rows) >= MINIMUM_CALIBRATION_SAMPLE else "INSUFFICIENT_SAMPLE",
                        "note": "This experiment is descriptive only; 16 games cannot establish calibration.",
                        "buckets": _calibration(calibration_rows)},
        "segments": {
            "byProfile": {profile: _segment([row for row in segment_rows if row["riskLevel"] == profile])
                          for profile in ("SAFE", "BALANCED", "AGGRESSIVE")},
            "byMarketPosition": {
                "favorite": _segment([row for row in segment_rows if row["entryPrice"] is not None and row["entryPrice"] < 0]),
                "underdog": _segment([row for row in segment_rows if row["entryPrice"] is not None and row["entryPrice"] > 0]),
            },
            "byEdgeSign": {
                "positive": _segment([row for row in segment_rows if row["modelEdge"] is not None and row["modelEdge"] > 0]),
                "nonPositive": _segment([row for row in segment_rows if row["modelEdge"] is not None and row["modelEdge"] <= 0]),
            },
        },
        "definitions": {"predictionPerformance": "All frozen winner predictions with verified final scores.",
                        "wageringPerformance": "One flat unit only when a legitimate pregame market observation qualifies under the frozen experiment profile.",
                        "roi": "Net units divided by total flat units risked; NO_BET observations are excluded."},
        "regularSeasonWeek1": regular_season_week1_feature_matrix(),
    }
