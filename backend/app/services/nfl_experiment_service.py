class ExperimentIntegrityError(RuntimeError):
    """Raised when official grading is blocked by a changed baseline."""


def _now() -> str:
    return datetime.now(timezone.utc).replace(microsecond=0).isoformat()


def _utc(value: str | datetime | None) -> datetime | None:
    if value in (None, ""):
        return None
    instant = value if isinstance(value, datetime) else datetime.fromisoformat(str(value).replace("Z", "+00:00"))
    if instant.tzinfo is None:
        instant = instant.replace(tzinfo=timezone.utc)
    return instant.astimezone(timezone.utc)


def _experiment_key(season: int, season_type: str, display_week: int) -> str:
    phase = str(season_type).strip().lower()
    prefix = "PRE" if phase == "preseason" else "REG"
    return f"NFL-{int(season)}-{prefix}{int(display_week)}"


def _safe_code(value: Any) -> str | None:
    if value in (None, ""):
        return None
    cleaned = re.sub(r"[^A-Za-z0-9_.:-]", "_", str(value))[:80]
    return cleaned or None


