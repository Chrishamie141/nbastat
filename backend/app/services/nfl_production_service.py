def run_lifecycle(*, season: int, season_type: str, week: int, generate: bool = True,
                  max_benchmark_games: int = 1) -> dict:
    schedule = _schedule(season, week, season_type)
    history = capture_prediction_history(season=season, season_type=season_type, week=week, schedule=schedule)
    new_results, provider_errors = 0, []
    initialize()
    with get_db_connection() as connection:
        complete_result_ids = {
            row["game_id"] for row in connection.execute(
                "SELECT game_id,player_stats_json FROM nfl_game_result_snapshots WHERE season=? AND season_type=? AND week=?",
                (season, season_type, week),
            ).fetchall() if json.loads(row["player_stats_json"] or "{}")
        }
    for game in schedule:
        if str(game.get("status") or "").lower() not in FINAL:
            continue
        if _gid(game.get("game_id") or game.get("id")) in complete_result_ids:
            continue
        try:
            detail = get_nfl_game_detail(str(game.get("game_id") or game.get("id")), force=True, trigger="production_lifecycle")
            new_results += int(persist_final(detail))
        except Exception as exc:
            provider_errors.append({"gameId": _gid(game.get("game_id") or game.get("id")), "error": type(exc).__name__})
            logger.exception("nfl_final_ingestion_failed", extra={"game_id": game.get("game_id") or game.get("id")})
    settlement = settle_predictions(season=season, season_type=season_type, week=week)
    benchmarks = generate_benchmarks(season=season, season_type=season_type, week=week, schedule=schedule,
                                     max_games=max_benchmark_games, max_tickets=1) if generate else {"created": 0, "noBet": 0, "retryableSkipped": 0}
    integrity = void_unverifiable_benchmarks(season=season, season_type=season_type, week=week)
    grading = grade_benchmarks(season=season, season_type=season_type, week=week)
    user_grading = grade_user_parlays(season=season, season_type=season_type, week=week)
    audit = audit_week(season=season, season_type=season_type, week=week, schedule=schedule)
    return {"history": history, "newFinalResults": new_results, "predictionSettlement": settlement,
            "benchmarks": benchmarks, "benchmarkIntegrity": integrity, "benchmarkGrading": grading, "userParlayGrading": user_grading,
            "providerErrors": provider_errors, "audit": audit}
